export function getDailyQuote(): string {
  const now = new Date();
  const start = new Date(now.getFullYear(), 0, 0);
  const diff = now.getTime() - start.getTime();
  const oneDay = 1000 * 60 * 60 * 24;
  const dayOfYear = Math.floor(diff / oneDay); // 1–365
  return DAILY_QUOTES[(dayOfYear - 1) % DAILY_QUOTES.length];
}

export function getGreeting(): { text: string; emoji: string; sub: string } {
  const hour = new Date().getHours();
  if (hour >= 5 && hour < 12) {
    return { text: 'Good morning', emoji: '', sub: 'Start your day with energy!' };
  } else if (hour >= 12 && hour < 17) {
    return { text: 'Good afternoon', emoji: '', sub: 'Keep up the great work!' };
  } else if (hour >= 17 && hour < 21) {
    return { text: 'Good evening', emoji: '', sub: 'Wind down and recharge.' };
  } else {
    return { text: 'Good night', emoji: '', sub: 'Rest well, you earned it!' };
  }
}
